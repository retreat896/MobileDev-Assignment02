# Generated by our friend, ChatGPT
class GroupLock:
    def __init__(self):
        self._cond = Condition()
        self._global_locked = False
        self._token_locks = defaultdict(lambda: Lock())
        self._active_token_count = 0

    def acquire_token(self, token):
        # wait if global lock is held, then mark active and acquire per-token lock
        with self._cond:
            while self._global_locked:
                self._cond.wait()
            self._active_token_count += 1
        # serialize access to this token
        self._token_locks[token].acquire()

    def release_token(self, token):
        # release per-token lock then update active count and notify
        try:
            self._token_locks[token].release()
        finally:
            with self._cond:
                self._active_token_count -= 1
                if self._active_token_count == 0:
                    self._cond.notify_all()

    def acquire_global(self):
        # wait until no active token locks, then take global flag
        with self._cond:
            while self._global_locked or self._active_token_count > 0:
                self._cond.wait()
            self._global_locked = True

    def release_global(self):
        with self._cond:
            self._global_locked = False
            self._cond.notify_all()

    @contextmanager
    def token(self, token):
        self.acquire_token(token)
        try:
            yield
        finally:
            self.release_token(token)

    @contextmanager
    def global_lock(self):
        self.acquire_global()
        try:
            yield
        finally:
            self.release_global()

