def init_download_thread():
    """Initialize download thread with its own event loop"""
    global download_loop
    download_loop = asyncio.new_event_loop()
    asyncio.set_event_loop(download_loop)
    download_loop.run_forever()

# Start download thread on startup
async def startup_event():
    global download_thread
    download_thread = Thread(target=init_download_thread, daemon=True)
    download_thread.start()
    
    # Wait for loop to be ready
    while download_loop is None:
        await asyncio.sleep(0.01)
    
    print("✅ Download thread initialized")

# Stop download thread on shutdown
async def shutdown_event():
    if download_loop:
        download_loop.call_soon_threadsafe(download_loop.stop)

# Manage the process over its lifetime (start; run; cleanup)
@asynccontextmanager
async def lifespan(app: FastAPI):
    await startup_event()
    try:
        yield
    finally:
        await shutdown_event()

